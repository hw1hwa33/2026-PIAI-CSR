export function getTerm(term) {
  return GLOSSARY[term] || null;
}

/* 기술 이름 앞에 붙일 쉬운 역할 이름 — 없으면 null */
export function roleOf(term) {
  const t = GLOSSARY[term];
  return t ? t.role : null;
}

